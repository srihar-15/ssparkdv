import { chromium, expect } from '@playwright/test';
import { products } from '../src/data.js';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({channel:'msedge'});
await mkdir('.tmp',{recursive:true});
const errors = [];
try {
 const page = await browser.newPage({viewport:{width:1440,height:1050}});
 page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://localhost:5173/cart');
 await expect(page.getByRole('heading',{name:'Your cart is waiting.'})).toBeVisible();
 await page.evaluate(items=>localStorage.setItem('spark-cart',JSON.stringify(items)),products.slice(0,2).map(p=>({...p,qty:1})));
 await page.reload();
 await expect(page.locator('.spark-cart-item')).toHaveCount(2);
 await page.getByRole('button',{name:'Increase Nanion Lite quantity',exact:true}).click();
 await expect(page.locator('.spark-cart-total')).toContainText('1,797');
 await page.reload();
 await expect(page.locator('.spark-cart-quantity').first()).toContainText('2');
 await page.screenshot({path:'.tmp/cart-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'.tmp/cart-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Cart overflows mobile viewport');
 await page.getByRole('link',{name:'Continue to checkout',exact:true}).click();
 await expect(page).toHaveURL(/checkout|login/);
 await page.goto('http://localhost:5173/cart');
 await page.getByRole('button',{name:'Remove Nanion Lite',exact:true}).click();
 await page.getByRole('button',{name:'Remove Nanion Elite',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your cart is waiting.'})).toBeVisible();
 const admin = await browser.newPage({viewport:{width:1440,height:1050}});
 admin.on('pageerror', e=>errors.push(e.message));
 await admin.goto('http://app.localhost:5173/login');
 await admin.locator('#staff-identifier').fill('admin');
 if (!process.env.SPARK_TEST_ADMIN_PASSWORD) throw Error('Set SPARK_TEST_ADMIN_PASSWORD to run the staff checks.');
 await admin.locator('#staff-password').fill(process.env.SPARK_TEST_ADMIN_PASSWORD);
 await admin.getByRole('button',{name:'Continue',exact:true}).click();
 await expect(admin.getByRole('heading',{name:'Business overview'})).toBeVisible({timeout:30000});
 await expect(admin.getByRole('button',{name:'Refresh orders',exact:true})).toBeEnabled({timeout:30000});
 await expect(admin.locator('.admin-error')).toHaveCount(0);
 await admin.screenshot({path:'.tmp/admin-desktop.png',fullPage:true});
 await admin.getByRole('button',{name:/Products/}).click();
 await expect(admin.locator('tbody tr')).toHaveCount(products.length);
 await admin.getByRole('textbox',{name:'Search products'}).fill('no-such-product');
 await expect(admin.getByText('No products match')).toBeVisible();
 await admin.getByRole('textbox',{name:'Search products'}).fill('Nanion Lite');
 await expect(admin.locator('tbody tr')).toHaveCount(products.filter(p=>p.name.includes('Nanion Lite')).length);
 await admin.getByRole('textbox',{name:'Search products'}).fill('');
 await admin.setViewportSize({width:390,height:844});
 await admin.screenshot({path:'.tmp/admin-mobile.png',fullPage:true});
 if(await admin.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Admin overflows mobile viewport');
 await admin.getByRole('link',{name:'Orders',exact:true}).click();
 await expect(admin).toHaveURL(/manage\/orders/);
 if(errors.length) throw Error(errors.join('\n'));
 console.log('PASS: real admin login and order data, product search, desktop/mobile layouts, cart quantities/persistence/removal and checkout navigation.');
} finally { await browser.close(); }
